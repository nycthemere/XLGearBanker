function XLGB_I18N:GetLanguage()
  local lang = GetCVar and GetCVar("language.2")
  if lang and strings[lang] then
    return lang
  end
  return "en"
end

function XLGB_I18N:Get(key, ...)
  local lang = XLGB_I18N:GetLanguage()
  local str = (strings[lang] and strings[lang][key]) or (strings["en"] and strings["en"][key]) or key
  if ... then
    return string.format(str, ...)
  end
  return str
end

function XLGB_GetString(key, ...)
  return XLGB_I18N:Get(key, ...)
end
